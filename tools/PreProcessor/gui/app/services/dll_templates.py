_INIT_HEAD_NOIBM = f"""//
//  unicones initial-condition DLL — pure fluid, NO immersed boundary
//  (generated by HybMesh PreProcessor)
//
#include <cmath>
using namespace std;

{PROTO_INIT}

void
initQ_at_p(double x, double y, double z,
           double* Q, double* dQdt,
           double* dQdx, double* dQdy, double* dQdz) {{
  const int nvar = 4;   // 2D fluid only — no solid-phase phi component
"""

_INIT_TAIL_NOIBM = """
  // Conservative vector Q = (rho, rho*u, rho*v, energy)   [no phi]
  Q[0] = rho;
  Q[1] = rho * u;
  Q[2] = rho * v;
  Q[3] = p / (gamma - 1.0) + 0.5 * rho * (u * u + v * v);

  for (int i = 0; i < nvar; ++i) { dQdt[i] = dQdx[i] = dQdy[i] = dQdz[i] = 0.0; }
}
"""


def _render_init_freestream_noibm(p: dict) -> str:
    return _INIT_HEAD_NOIBM + f"""  const double mach = {_n(p['mach'])};
  const double gamma = {_n(p['gamma'])};
  const double T = 1.0;

  double rho = {_n(p['rho'])};
  double u = {_n(p['u'])};
  double v = {_n(p['v'])};
  double p = rho * T / (gamma * mach * mach);
""" + _INIT_TAIL_NOIBM


def _render_init_shock_noibm(p: dict) -> str:
    return _INIT_HEAD_NOIBM + f"""  const double gamma = {_n(p['gamma'])};
  const double mach = {_n(p['mach'])};
  const double x0 = {_n(p['x0'])};        // shock at x = x0 (x < x0 = pre-shock)
  const double T2T1 = {_n(p['t2t1'])};    // post/pre temperature ratio
  const double r2r1 = {_n(p['r2r1'])};    // post/pre density ratio
  const double pre_p = 1.0 / (gamma * mach * mach);

  double rho, u, v, p;
  if (x < x0) {{                          // pre-shock (freestream)
    rho = 1.0; u = 1.0; v = 0.0;
    p = pre_p;
  }} else {{                              // post-shock
    rho = r2r1; u = 0.0; v = 0.0;
    p = rho * T2T1 / (gamma * mach * mach);
  }}
""" + _INIT_TAIL_NOIBM


