def poly_area(ring):
    """Twice the enclosed area of a closed polygon, by the shoelace."""
    return abs(sum(ring[k][0] * ring[(k + 1) % len(ring)][1]
                   - ring[(k + 1) % len(ring)][0] * ring[k][1]
                   for k in range(len(ring))))


