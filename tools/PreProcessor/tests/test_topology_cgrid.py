def context(fixname, first_cell=1e-3, extra=()):
    """``(the section's path, a context loading it)`` — plus any far field named.

    The far field is a SECOND geometry of the mesh, exactly as the O-grid's is, so
    a spread entry that binds one has to load it: a context that did not would
    refuse with "not one of this mesh's geometries", which is a real refusal about
    the wrong thing.
    """
    path = FIX[fixname]
    return path, tb.context_for_config(Cfg([path] + list(extra), first_cell))


